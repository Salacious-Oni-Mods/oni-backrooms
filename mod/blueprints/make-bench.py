#!/usr/bin/env python3
"""Writes the two KENNEL BENCH canvases (bench-vanilla.yaml, bench-kennel.yaml) beside this script.

The design: 17 identical Stables of 84 cells, each with a Grooming Station and a
Critter Feeder, 18 hatches per pen (306) and one rancher per pen (17) spawned by the rig. The vanilla arm has no
Kennel; the Kennel arm is the same world with one Kennel per pen. Nothing else differs, so the two
yamls are written from one layout and diffed by the rig only in the Kennel lines.

Layout (must match BenchLayout in KennelBenchRig.cs):
  two columns of pens around one ladder shaft at x 17; column 0 interiors x 2..15, column 1
  x 19..32; row r interior y 2+7r .. 7+7r (14 x 6 = 84 cells), a 1-cell Obsidian floor between
  rows. Pen i is column i % 2, row i // 2; the 18th slot (row 8, column 1) stays solid. Each pen has
  one Pneumatic Door in the wall facing the shaft, at its floor (critters cannot pass a door that
  is not set Open: Door.cs, Grid.CritterImpassable). Drywall behind all 84 cells of every pen in
  BOTH arms, because the Kennel needs a backwall and the arms must differ only in the Kennel.

Run: python3 make-bench.py   (deterministic; the yamls are committed)
"""
import os

PENS = 17
COL_X0 = (2, 19)
PEN_W, PEN_H = 14, 6
ROW_PITCH = 7
SHAFT_X = 17
WALL_X = (16, 18)          # the wall between each column and the shaft, where the door goes
KENNEL_LX = 3              # 3x3, origin bottom-centre: covers lx 2..4
FEEDER_LX = 7              # 1x2
STATION_LX = 10            # 2x3: covers lx 10..11
WIDTH, HEIGHT = 36, 66


def pen_origin(i):
    return COL_X0[i % 2], 2 + ROW_PITCH * (i // 2)


def building(lines, bid, x, y, element):
    lines += [f"  - id: {bid}", f"    x: {x}", f"    y: {y}", f"    element: {element}",
              "    temperature: 300.0"]


def write(path, kennels):
    arm = "Kennel" if kennels else "vanilla"
    top = 2 + ROW_PITCH * ((PENS - 1) // 2) + PEN_H - 1
    out = [
        f"# KENNEL BENCH, {arm} arm (--backrooms-bench-{'kennel' if kennels else 'vanilla'}).",
        "# GENERATED by make-bench.py; edit that, not this. 17 Stables of 84 cells (14 x 6), each with",
        "# a Grooming Station, a Critter Feeder" + (" and a Kennel" if kennels else " (no Kennel)")
        + ", drywalled; 306 hatches and 17 ranchers are",
        "# spawned by the rig. Pens open onto one ladder shaft through a Pneumatic Door each.",
        f"name: KennelBench{'Kennel' if kennels else 'Vanilla'}",
        "",
        "canvas:",
        f"  width: {WIDTH}",
        f"  height: {HEIGHT}",
        "  background: Vacuum",
        "  backgroundTemperature: 300.0",
        "  border: Unobtanium",
        "  borderThickness: 1",
        "  zone: Sandstone",
        f"  startX: {SHAFT_X}",
        "  startY: 30",
        "",
        "regions:",
        "  - name: block",
        "    x: 1",
        "    y: 1",
        f"    w: {WIDTH - 2}",
        f"    h: {HEIGHT - 2}",
        "  - name: shaft",
        f"    x: {SHAFT_X}",
        "    y: 2",
        "    w: 1",
        f"    h: {top - 1}",
    ]
    for i in range(PENS):
        x0, y0 = pen_origin(i)
        out += [f"  - name: pen{i:02d}", f"    x: {x0}", f"    y: {y0}", f"    w: {PEN_W}", f"    h: {PEN_H}"]
        out += [f"  - name: door{i:02d}", f"    x: {WALL_X[i % 2]}", f"    y: {y0}", "    w: 1", "    h: 2"]
    out += ["", "fills:",
            "  - region: block", "    element: Obsidian", "    mass: 1840.0", "    temperature: 300.0",
            "  - region: shaft", "    element: Oxygen", "    mass: 1.2", "    temperature: 300.0"]
    for i in range(PENS):
        for r in (f"pen{i:02d}", f"door{i:02d}"):
            out += [f"  - region: {r}", "    element: Oxygen", "    mass: 1.2", "    temperature: 300.0"]
    out += ["", "buildings:"]
    for y in range(2, top + 1):
        building(out, "Ladder", SHAFT_X, y, "SandStone")
    for i in range(PENS):
        x0, y0 = pen_origin(i)
        for dy in range(PEN_H):
            for dx in range(PEN_W):
                building(out, "ExteriorWall", x0 + dx, y0 + dy, "SandStone")
        building(out, "Door", WALL_X[i % 2], y0, "Steel")
        building(out, "RanchStation", x0 + STATION_LX, y0, "Steel")
        building(out, "CreatureFeeder", x0 + FEEDER_LX, y0, "IronOre")
        if kennels:
            building(out, "BackroomsKennel", x0 + KENNEL_LX, y0, "Steel")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


here = os.path.dirname(os.path.abspath(__file__))
write(os.path.join(here, "bench-vanilla.yaml"), kennels=False)
write(os.path.join(here, "bench-kennel.yaml"), kennels=True)
